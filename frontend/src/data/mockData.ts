export const PEAK_HOURS_DATA = Array.from({ length: 7 }, (_, dayIdx) =>
  Array.from({ length: 24 }, (_, hour) => {
    const days = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'];
    let intensity = 0;
    if (hour >= 9 && hour <= 18 && dayIdx < 5) {
      intensity = Math.random() * 0.8 + 0.1;
      if (hour >= 10 && hour <= 12) intensity = Math.min(1, intensity + 0.3);
      if (hour >= 14 && hour <= 16) intensity = Math.min(1, intensity + 0.2);
    } else if (dayIdx < 5 && hour >= 19 && hour <= 22) {
      intensity = Math.random() * 0.4;
    }
    return { day: days[dayIdx], hour, intensity };
  })
);

